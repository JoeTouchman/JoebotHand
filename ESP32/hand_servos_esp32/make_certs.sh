#!/bin/bash
# Makes the hand's TLS certificates. Run once; run again to replace them
# (then reinstall joebotics-ca.crt on your phone and re-upload the sketch).
#
#   certs/joebotics-ca.key/.crt  A small local certificate authority. Install
#                                joebotics-ca.crt on your phone once to get rid of
#                                the certificate warning and to allow the service
#                                worker (offline caching). It is name-constrained
#                                to 192.168.4.1, so even a leaked key can't vouch
#                                for any other site.
#   certs/server.key/.crt        The ESP32's certificate for 192.168.4.1, signed by
#                                that CA. 825 days: iPhones reject server
#                                certificates valid for longer.
#   certs.h                      Server certificate chain + key + CA certificate,
#                                compiled into the firmware.
#
# EC P-256 keys: small, and quick for the ESP32 to handshake with.
# Everything this writes is gitignored - it includes private keys.
set -euo pipefail
cd "$(dirname "$0")"
mkdir -p certs
cd certs

cat > ca.cnf <<'EOF'
[req]
distinguished_name = dn
prompt = no
x509_extensions = ext
[dn]
CN = Joebotics Local CA
O = Joebotics
[ext]
basicConstraints = critical, CA:TRUE, pathlen:0
keyUsage = critical, keyCertSign, cRLSign
subjectKeyIdentifier = hash
nameConstraints = critical, permitted;IP:192.168.4.1/255.255.255.255
EOF

cat > server.cnf <<'EOF'
[req]
distinguished_name = dn
prompt = no
[dn]
CN = 192.168.4.1
O = Joebotics
[ext]
basicConstraints = critical, CA:FALSE
keyUsage = critical, digitalSignature
extendedKeyUsage = serverAuth
subjectAltName = IP:192.168.4.1
subjectKeyIdentifier = hash
authorityKeyIdentifier = keyid
EOF

# 1. Local CA, valid 10 years
openssl ecparam -name prime256v1 -genkey -noout -out joebotics-ca.key
openssl req -x509 -new -key joebotics-ca.key -sha256 -days 3650 -config ca.cnf -out joebotics-ca.crt

# 2. Server certificate for 192.168.4.1, valid 825 days, signed by the CA
openssl ecparam -name prime256v1 -genkey -noout -out server.key
openssl req -new -key server.key -config server.cnf -out server.csr
openssl x509 -req -in server.csr -CA joebotics-ca.crt -CAkey joebotics-ca.key -CAcreateserial \
  -days 825 -sha256 -extfile server.cnf -extensions ext -out server.crt
openssl verify -CAfile joebotics-ca.crt server.crt

# 3. certs.h for the firmware (chain = server cert, then CA cert)
{
  echo "// Generated by make_certs.sh - gitignored: contains the server's private key."
  echo "#pragma once"
  echo "static const char SERVER_CERT_PEM[] = R\"PEM("
  cat server.crt joebotics-ca.crt
  echo ")PEM\";"
  echo "static const char SERVER_KEY_PEM[] = R\"PEM("
  cat server.key
  echo ")PEM\";"
  echo "static const char CA_CERT_PEM[] = R\"PEM("
  cat joebotics-ca.crt
  echo ")PEM\";"
} > ../certs.h
echo "wrote certs/ and certs.h"
